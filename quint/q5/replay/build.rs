//! Snapshot the exact production source of the functions under test.
//!
//! Sources:
//! - stock: the registry `midnight-proofs-0.8.3` crate source (cargo cache);
//! - loki:  `git show a256a9a:<path>` from this repository's object database;
//! - w10:   `git show 5e37ead:<path>` (unmerged `cuda-argument-commit` head).
//!
//! The only edits are textual, asserted to apply exactly once, and listed in
//! `REPLACEMENTS` comments below: the lookup `HashMap` is swapped for an
//! order-injectable shim map (so stock and Loki can be compared over the *same*
//! iteration order), and `cfg(feature = ...)` lines are resolved per variant.
use std::{env, fs, path::PathBuf, process::Command};

const LOKI_REV: &str = "a256a9a";
const W10_REV: &str = "5e37ead";

fn git_show(rev: &str, path: &str) -> String {
    let root = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").unwrap()).join("../../..");
    let out = Command::new("git")
        .args(["show", &format!("{rev}:{path}")])
        .current_dir(root)
        .output()
        .expect("git show");
    assert!(out.status.success(), "missing pinned source {rev}:{path}");
    String::from_utf8(out.stdout).unwrap()
}

fn stock(path: &str) -> String {
    let home = env::var("CARGO_HOME")
        .unwrap_or_else(|_| format!("{}/.cargo", env::var("HOME").unwrap()));
    let reg = PathBuf::from(home).join("registry/src");
    for entry in fs::read_dir(&reg).unwrap() {
        let p = entry.unwrap().path().join("midnight-proofs-0.8.3").join(path);
        if p.exists() {
            println!("cargo:rerun-if-changed={}", p.display());
            return fs::read_to_string(p).unwrap();
        }
    }
    panic!("stock midnight-proofs-0.8.3 source not in cargo registry cache");
}

/// Return the item starting at `start` through its matching closing brace.
fn item(src: &str, start: &str) -> String {
    let s = src.find(start).unwrap_or_else(|| panic!("marker not found: {start}"));
    assert_eq!(src.matches(start).count(), 1, "marker not unique: {start}");
    let bytes = src.as_bytes();
    let mut i = s + src[s..].find('{').unwrap();
    let mut depth = 0i32;
    let (mut in_str, mut in_line_comment) = (false, false);
    loop {
        let c = bytes[i] as char;
        if in_line_comment {
            if c == '\n' {
                in_line_comment = false;
            }
        } else if in_str {
            if c == '\\' {
                i += 1;
            } else if c == '"' {
                in_str = false;
            }
        } else if c == '/' && bytes[i + 1] as char == '/' {
            in_line_comment = true;
        } else if c == '"' {
            in_str = true;
        } else if c == '{' {
            depth += 1;
        } else if c == '}' {
            depth -= 1;
            if depth == 0 {
                return src[s..=i].to_string();
            }
        }
        i += 1;
    }
}

/// Return the text from `start` (inclusive) to `end` (exclusive), searching
/// only after the unique `anchor`.
fn region(src: &str, anchor: &str, start: &str, end: &str) -> String {
    assert_eq!(src.matches(anchor).count(), 1, "anchor not unique: {anchor}");
    let a = src.find(anchor).unwrap();
    let s = a + src[a..].find(start).unwrap_or_else(|| panic!("start not found: {start}"));
    let e = s + src[s..].find(end).unwrap_or_else(|| panic!("end not found: {end}"));
    src[s..e].to_string()
}

fn replace_once(code: String, from: &str, to: &str) -> String {
    assert_eq!(code.matches(from).count(), 1, "replacement must apply once: {from}");
    code.replace(from, to)
}

const MAP_FROM: &str = "HashMap::<F, u32>::with_capacity(table_expression.len())";
const MAP_TO: &str = "ShimMap::<F, u32>::with_capacity(table_expression.len())";
const DEFAULT_CFG: &str = "#[cfg(not(feature = \"loki-deterministic-lookup-order\"))]";
const DET_CFG: &str = "#[cfg(feature = \"loki-deterministic-lookup-order\")]";

fn header(origin: &str) -> String {
    format!("// GENERATED by build.rs from {origin}. Do not edit.\n#[allow(unused_imports)] use crate::shim::*;\n")
}

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    let out = PathBuf::from(env::var_os("OUT_DIR").unwrap());
    let w = |name: &str, code: String| fs::write(out.join(name), code).unwrap();

    // ---- lookup: permute_expression_pair ---------------------------------
    let s_lookup = stock("src/plonk/lookup/prover.rs");
    let l_lookup = git_show(LOKI_REV, "src/plonk/lookup/prover.rs");
    let w_lookup = git_show(W10_REV, "src/plonk/lookup/prover.rs");
    let perm_sig = "fn permute_expression_pair<";
    let s_perm = replace_once(item(&s_lookup, perm_sig), MAP_FROM, MAP_TO);
    let l_perm = replace_once(item(&l_lookup, perm_sig), MAP_FROM, MAP_TO);
    let w_perm = replace_once(item(&w_lookup, perm_sig), MAP_FROM, MAP_TO);
    let l_default = replace_once(replace_once(l_perm.clone(), DEFAULT_CFG, "#[cfg(all())]"), DET_CFG, "#[cfg(any())]");
    let l_det = replace_once(replace_once(l_perm, DEFAULT_CFG, "#[cfg(any())]"), DET_CFG, "#[cfg(all())]");
    w("stock_permute.rs", header("stock 0.8.3 src/plonk/lookup/prover.rs") + "pub " + &s_perm);
    w("loki_permute_default.rs", header("a256a9a src/plonk/lookup/prover.rs, default cfg") + "pub " + &l_default);
    w("loki_permute_det.rs", header("a256a9a src/plonk/lookup/prover.rs, loki-deterministic-lookup-order") + "pub " + &l_det);
    w("w10_permute.rs", header("5e37ead src/plonk/lookup/prover.rs") + "pub " + &w_perm);

    // ---- lookup: commit_product body ------------------------------------
    let product = |src: &str, origin: &str, imports: &str| {
        let body = region(src, "pub(crate) fn commit_product<", "let blinding_factors = pk.vk.cs.blinding_factors();", "let product_commitment = CS::commit_lagrange(params, &z);");
        header(origin) + imports + "\npub struct Permuted<F> {\n    pub compressed_input_expression: Polynomial<F, LagrangeCoeff>,\n    pub permuted_input_expression: Polynomial<F, LagrangeCoeff>,\n    pub compressed_table_expression: Polynomial<F, LagrangeCoeff>,\n    pub permuted_table_expression: Polynomial<F, LagrangeCoeff>,\n}\nimpl<F: WithSmallOrderMulGroup<3> + FromUniformBytes<64>> Permuted<F> {\n    pub fn product(self, pk: &ProvingKey<F, Pcs>, beta: F, gamma: F, rng: &mut (impl RngCore + CryptoRng)) -> Vec<F> {\n        " + &body + "\n        z.values\n    }\n}\n"
    };
    w("stock_product.rs", product(&s_lookup, "stock 0.8.3 Permuted::commit_product", "use crate::stock_arith::parallelize;"));
    w("loki_product.rs", product(&l_lookup, "a256a9a Permuted::commit_product", "use crate::loki_arith::{batch_invert_parallel, parallelize, prefix_product};"));

    // ---- permutation: Argument::commit body ------------------------------
    let s_pp = stock("src/plonk/permutation/prover.rs");
    let l_pp = git_show(LOKI_REV, "src/plonk/permutation/prover.rs");
    let w_pp = git_show(W10_REV, "src/plonk/permutation/prover.rs");
    let perm = |src: &str, origin: &str, imports: &str| {
        let body = region(src, "pub(crate) fn commit<", "let domain = &pk.vk.domain;", "let permutation_product_commitment");
        header(origin) + imports + "\npub struct PermArgument {\n    pub columns: Vec<PermColumn>,\n}\nimpl PermArgument {\n    #[allow(unused_variables, unused_mut, clippy::all)]\n    pub fn commit_shim<F: WithSmallOrderMulGroup<3>>(&self, pk: &ProvingKey<F, Pcs>, pkey: &PermProvingKey<F>, advice: &[Polynomial<F, LagrangeCoeff>], fixed: &[Polynomial<F, LagrangeCoeff>], instance: &[Polynomial<F, LagrangeCoeff>], beta: F, gamma: F, rng: &mut (impl RngCore + CryptoRng)) -> Vec<Vec<F>> {\n        let mut __out: Vec<Vec<F>> = Vec::new();\n        " + &body + "\n        __out.push(z.values.clone());\n        sets.push(());\n        }\n        __out\n    }\n}\n"
    };
    w("stock_perm.rs", perm(&s_pp, "stock 0.8.3 permutation Argument::commit", "use crate::stock_arith::parallelize;"));
    w("loki_perm.rs", perm(&l_pp, "a256a9a permutation Argument::commit", "use crate::loki_arith::{batch_invert_parallel, parallelize, prefix_product};"));
    // W10 inserts only cfg-gated commit lines after this region; assert that.
    assert_eq!(
        region(&w_pp, "pub(crate) fn commit<", "let domain = &pk.vk.domain;", "let z = domain.lagrange_from_vec(modified_values);"),
        region(&l_pp, "pub(crate) fn commit<", "let domain = &pk.vk.domain;", "let z = domain.lagrange_from_vec(modified_values);"),
        "W10 permutation product body differs from main"
    );
    let w_after = region(&w_pp, "pub(crate) fn commit<", "let z = domain.lagrange_from_vec(modified_values);", "sets.push(");
    w("w10_perm_tail.txt", w_after);

    // ---- arithmetic helpers ---------------------------------------------
    let s_ar = stock("src/utils/arithmetic.rs");
    let l_ar = git_show(LOKI_REV, "src/utils/arithmetic.rs");
    let par = "pub fn parallelize<T: Send, F: Fn(&mut [T], usize) + Send + Sync + Clone>";
    assert_eq!(item(&s_ar, par), item(&l_ar, par), "parallelize changed");
    w("stock_arith.rs", header("stock 0.8.3 src/utils/arithmetic.rs") + &item(&s_ar, par) + "\n");
    w(
        "loki_arith.rs",
        header("a256a9a src/utils/arithmetic.rs")
            + &item(&l_ar, par)
            + "\n"
            + &item(&l_ar, "pub(crate) fn batch_invert_parallel<").replace("pub(crate) fn", "pub fn")
            + "\n"
            + &item(&l_ar, "pub(crate) fn prefix_product<").replace("pub(crate) fn", "pub fn")
            + "\n",
    );

    // ---- batch_invert_rational --------------------------------------------
    let s_poly = stock("src/poly/mod.rs");
    let l_poly = git_show(LOKI_REV, "src/poly/mod.rs");
    w(
        "stock_rational.rs",
        header("stock 0.8.3 src/poly/mod.rs")
            + &item(&s_poly, "pub(crate) fn batch_invert_rational<").replace("pub(crate) fn", "pub fn")
            + "\n"
            + &item(&s_poly, "impl<F: Field> Polynomial<Rational<F>, LagrangeCoeff> {").replace("pub(crate) fn", "pub fn")
            + "\n",
    );
    w(
        "loki_rational.rs",
        header("a256a9a src/poly/mod.rs")
            + "use crate::loki_arith::batch_invert_parallel;\n"
            + &item(&l_poly, "pub(crate) fn batch_invert_rational<").replace("pub(crate) fn", "pub fn")
            + "\n",
    );

    // ---- W10 commit_argument (compiled against the Loki main public API) --
    let w_commit = git_show(W10_REV, "src/poly/commitment.rs");
    let ca = item(&w_commit, "pub(crate) fn commit_argument<");
    let ca = ca
        .replace("pub(crate) fn", "pub fn")
        .replace("    #[cfg(feature = \"loki-profile\")]\n    let size = values.len();\n", "")
        .replace("        #[cfg(feature = \"loki-profile\")]\n        crate::profile::record_backend(\"argument_commit.coeff\", size);\n", "")
        .replace("        #[cfg(feature = \"loki-profile\")]\n        crate::profile::record_backend(\"argument_commit.lagrange\", size);\n", "");
    assert!(!ca.contains("cfg("), "unexpected cfg left in commit_argument: {ca}");
    w(
        "w10_commit_argument.rs",
        "// GENERATED by build.rs from 5e37ead src/poly/commitment.rs (loki-profile hooks removed).\n\
         use ff::WithSmallOrderMulGroup;\n\
         use loki::poly::{commitment::{Params, PolynomialCommitmentScheme}, Coeff, EvaluationDomain, LagrangeCoeff, Polynomial};\n"
            .to_string()
            + &ca
            + "\n",
    );
}
